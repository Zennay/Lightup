def build(args):
    path=Path(args.output)
    if not path.is_absolute() or path.suffix.lower()!=".html":
        reject("PRIVATE HOLD: absolute NEW .html software output required")
    private_parent(str(path.parent))
    if path==ROOT or ROOT in path.parents:
        reject("PRIVATE HOLD: no source repository overwrite")
    raw=render().encode("utf-8")
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW|os.O_CLOEXEC,0o600)
    try:
        os.fchmod(fd,0o600)
        done=0
        while done<len(raw):done+=os.write(fd,raw[done:])
        os.fsync(fd)
    finally:os.close(fd)
    print("PRIVATE HOLD: source-free HUMAN reply operator inbox viewer built; no source transmitted")
    print(str(path),"unsigned software SHA256",hashlib.sha256(raw).hexdigest())
    return 2


