def js_source():
    fd=os.open(ROOT/JS,os.O_RDONLY|os.O_NOFOLLOW|os.O_CLOEXEC|os.O_NONBLOCK)
    try:
        before=os.fstat(fd)
        if not stat.S_ISREG(before.st_mode) or not 1<=before.st_size<=MAX:
            reject("PRIVATE HOLD: invalid original owner inbox software source")
        chunks=bytearray()
        while True:
            value=os.read(fd,65536)
            if not value:break
            chunks.extend(value)
            if len(chunks)>MAX:reject("PRIVATE HOLD: oversized original owner inbox software")
        after=os.fstat(fd)
        fields=("st_dev","st_ino","st_size","st_mtime_ns","st_ctime_ns")
        if any(getattr(before,k)!=getattr(after,k) for k in fields) or len(chunks)!=before.st_size:
            reject("PRIVATE HOLD: original owner inbox software changed during read")
        return bytes(chunks).decode("utf-8")
    finally:
        os.close(fd)


