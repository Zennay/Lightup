#!/usr/bin/env python3
"""Private LOCAL original evidence subset dossier; never external publication."""
from __future__ import annotations
import argparse
import html
import os
from pathlib import Path
import shutil
import sys
import tempfile
from suite import Hold, ROOT, source, parent_dir, read_safe, original

CURATE = ROOT / "assessment-evidence-curation" / "curate.py"
REQUIRED = (
    ("Selected-only PRIVATE finding dossier", "PRIVATE-curated-dossier.html"),
    ("Minimal PRIVATE HUMAN recipient handoff", "PRIVATE-source-minimized-HUMAN-handoff.html"),
    ("Original unsigned curation receipt", "PRIVATE-curation-receipt.json"),
    ("Source-free PRIVATE counts", "anonymous-counts-PRIVATE.json"),
)
OPTIONAL = (
    ("Routine priority HUMAN page", "PRIVATE-HUMAN-routine-priority.html"),
    ("Soon priority HUMAN page", "PRIVATE-HUMAN-soon-priority.html"),
    ("Urgent priority HUMAN page", "PRIVATE-HUMAN-urgent-priority.html"),
)

def prepare(args: argparse.Namespace) -> int:
    parent = parent_dir(args.private_parent)
    briefing_kit = parent_dir(args.original_kit)
    curation_kit = parent_dir(args.curation_kit)
    original_file = source(args.source)
    human_selection = Path(args.selection).absolute()
    read_safe(human_selection, 2 * 1024 * 1024)
    manifest = briefing_kit / "briefing" / "manifest.json"
    worksheet = briefing_kit / "briefing" / "human-followup.csv"
    receipt = curation_kit / "curation" / "selection-receipt.json"
    for path in (CURATE, manifest, worksheet, receipt):
        read_safe(path, 2 * 1024 * 1024)
    kit = Path(tempfile.mkdtemp(prefix="PRIVATE-lightup-selected-", dir=parent))
    os.chmod(kit, 0o700)
    complete = False
    try:
        original(CURATE, [
            "publish", "--source", original_file, "--manifest", str(manifest),
            "--worksheet", str(worksheet), "--selection-receipt", str(receipt),
            "--selection", str(human_selection), "--output-dir", str(kit / "selected"),
        ])
        for _, name in REQUIRED:
            read_safe(kit / "selected" / name, 2 * 1024 * 1024)
        links = list(REQUIRED)
        for title, name in OPTIONAL:
            if (kit / "selected" / name).exists():
                read_safe(kit / "selected" / name, 2 * 1024 * 1024)
                links.append((title, name))
        html_links = "".join(
            "<li><a href='selected/" + html.escape(name, quote=True) + "'>" +
            html.escape(title) + "</a></li>"
            for title, name in links
        )
        doc = ("""<!doctype html><html lang="en"><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; form-action 'none'; connect-src 'none'">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>LightUp PRIVATE source-bound HUMAN dossier</title>
<style>body{max-width:820px;margin:3rem auto;padding:1rem;font:17px/1.6 system-ui}
li{margin:.7rem 0}a{color:#155c83}.hold{color:#873c20;font-weight:bold}</style>
<h1>LightUp PRIVATE selected evidence dossier</h1>
<p class="hold">REVIEW_ONLY / HOLD — NOT an assessment, verification, grant,
source signature, consent or release.</p><ul>""" + html_links + """</ul>
<p>Original finding detail exists in the PRIVATE dossier. The separate minimal
HUMAN handoff is still PRIVATE and requires deliberate client/operator authorization,
confidentiality review and action-time revocation before any disclosure.
Human priority or selection does not mean a vulnerability is verified or fixed.</p>
<p>Only pre-existing lab files were locally read. No external publication, target
interaction, model, grant, scan, retest or deletion occurred. INCUBATE M3/M7 ·
PLAN/LAB ONLY · DRAFT/HOLD.</p></html>""")
        fd = os.open(kit / "OPEN-PRIVATE.html", os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as out:
            out.write(doc)
        complete = True
        print("REVIEW_ONLY: selected-only ORIGINAL PRIVATE HUMAN dossier prepared.")
        print("OPEN LOCALLY: " + str(kit / "OPEN-PRIVATE.html"))
        return 2
    finally:
        if not complete:
            shutil.rmtree(kit)

def main() -> int:
    cli = argparse.ArgumentParser(description="PRIVATE selected evidence handoff; never an external publish")
    cli.add_argument("--source", required=True, help="unchanged original PRIVATE lab source")
    cli.add_argument("--original-kit", required=True, help="PRIVATE kit prepared using suite.py --brief")
    cli.add_argument("--curation-kit", required=True, help="PRIVATE kit generated by curation.py")
    cli.add_argument("--selection", required=True, help="HUMAN completed private source-bound CSV")
    cli.add_argument("--private-parent", required=True, help="existing owner-only mode 0700 directory")
    args = cli.parse_args()
    try:
        return prepare(args)
    except (Hold, OSError, ValueError) as exc:
        print(str(exc) if isinstance(exc, Hold) else "HOLD: private selected dossier refused",
              file=sys.stderr)
        return 3

if __name__ == "__main__":
    raise SystemExit(main())
